def tr(key: str, lang: str) -> str:
    """Return the German or English translation for *key*."""
    return TR[key][0 if lang == "de" else 1]


def missing_keys(lang: str = "de") -> list[str]:
    """Return keys whose translation is empty or missing."""
    index = 0 if lang == "de" else 1
    return [key for key, values in TR.items() if not values[index].strip()]
